for (const [text, want] of CASES) test(text, () => assert.equal(say(read(text.replaceAll('^', KEY))), want));

test('a shortcut that is not marked', () => assert.equal(say(read('Hide the sidebar · ⌘\\')), '*Hide the sidebar | [⌘\\]'));
test('a level as it is dragged', () => {
  assert.equal(say(read('Left deck low EQ · −6.0 dB')), '*Left deck low | −6.0 dB');
  assert.equal(say(read('Crossfader · 40% to the left deck')), '*Crossfader | 40% left');
});
test('a sentence it has not met is still shown', () => {
  assert.equal(say(read('Something new that no rule knows about, said in a sentence')), '(Something new that no rule knows about, said in a sentence.)');
  assert.equal(say(read(`Something new · ${KEY}J · and what it does when you press it`)), '*Something new | [J] | (And what it does when you press it.)');
});
